    public infante CrearInfante(){
        DefaultTableModel modelo = (DefaultTableModel) T_query.getModel();
        int ren = T_query.getSelectedRow();
        infante kid = new infante();
        
        
        if (ren >= 0) {
            kid.curp = modelo.getValueAt(ren, 0).toString();
            kid.nombre = modelo.getValueAt(ren, 1).toString();
            kid.sexo = modelo.getValueAt(ren, 2).toString();
            kid.fecha_nac = modelo.getValueAt(ren, 3).toString();
            kid.estado = modelo.getValueAt(ren, 4).toString();
        }
        else{
            JOptionPane.showConfirmDialog(this, "selecciona un renglon de la tabla");
        }
        return  kid;
    }
    
