    private void B_editarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_B_editarActionPerformed
      
        if (T_query.getSelectedRow() < 0) {
            JOptionPane.showMessageDialog(this, "primero seleciona un renglon de la tabla");
            return;
        }
        if (TB_infantes.isSelected()) {
            JDinfantes di = new JDinfantes(this, true);
            di.ObtenerConexion(cnx);
            di.ObtenerInfante(CrearInfante());
            di.setVisible(true);
            
            cnx.entablar(infante.todos, T_query);
           
        }
        else if (TB_educadores.isSelected()) {
            JDeducadores de = new JDeducadores(this, true);
            de.ObtenerConexion(cnx);
            de.ObtenerEducador(CrearEducador());
            de.setVisible(true);
            
            cnx.entablar(educador.todos, T_query);
        }
        else if (TB_responsables.isSelected()) {
            JDresponsables dr = new JDresponsables(this, true);
            dr.ObtenerConexion(cnx);
            dr.ObtenerResponsable(CrearResponsable());
            dr.setVisible(true);
            
            cnx.entablar(responsable.todos, T_query);
        }
        else if (TB_bitacora.isSelected()) {
            JDbitacora db = new JDbitacora(this, true);
            db.ObtenerConexion(cnx);
            db.ObtenerBitacora(CrearBitacora());
            db.setVisible(true);
            
            cnx.entablar(bitacora.todos, T_query);
        }
    }//GEN-LAST:event_B_editarActionPerformed

