    private void B_registrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_B_registrarActionPerformed
       responsable res = new responsable(
       T_curpr.getText(),
       T_nombrer.getText(),
       CB_sexor.getSelectedItem().toString(),
       T_telefonor.getText(),
       T_parentesco.getText(),
       CB_estado.getSelectedItem().toString()
       );
        
        if (res.insertar(cnx.con)==1) {
            JOptionPane.showMessageDialog(this,"responsable registrado");
            this.dispose();
        }
        else{
            JOptionPane.showMessageDialog(this,"error de registro");
        }
    }//GEN-LAST:event_B_registrarActionPerformed

