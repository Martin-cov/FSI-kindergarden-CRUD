    private void B_registrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_B_registrarActionPerformed

       bitacora  Bit = new bitacora(
       J_tiempo.getText(),
       CB_tipo.getSelectedItem().toString(),
       TX_observaciones.getText(),
       CB_infante.getSelectedItem().toString(),
       CB_responsable.getSelectedItem().toString(),
       CB_educadores.getSelectedItem().toString()
       );
        
        if (Bit.insertar(cnx.con)==1) {
            JOptionPane.showMessageDialog(this,"bitacora registrada");
            this.dispose();
        }
        else{
            JOptionPane.showMessageDialog(this,"error de registro");
        }
    }//GEN-LAST:event_B_registrarActionPerformed

