    public void ObtenerConexion(Conexion cnx){
        this.cnx = cnx;
        
        cnx.seleccionar(infante.curpi, CB_infante);
        cnx.seleccionar(responsable.curprr, CB_responsable);
        cnx.seleccionar(educador.curpee, CB_educadores);
        
    }
    public void ObtenerBitacora(bitacora bit){
        J_folio1.setText(bit.folio);
        J_tiempo.setText(bit.tiempo);
        CB_tipo.setSelectedItem(bit.tipo);
        TX_observaciones.setText(bit.observaciones);
        CB_infante.setSelectedItem(bit.infantes_curp);
        CB_responsable.setSelectedItem(bit.responsables_curpr);
        CB_educadores.setSelectedItem(bit.educadores_curpe);
    }

